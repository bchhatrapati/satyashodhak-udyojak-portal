import re
from datetime import date, datetime
from decimal import Decimal
from typing import Optional

from pydantic import (
    BaseModel,
    EmailStr,
    Field,
    field_validator,
    ConfigDict,
    HttpUrl,
)


# --- 1. BASE SCHEMA ---
# Contains fields that are common to all operations.
class MemberBase(BaseModel):
    full_name: str = Field(..., min_length=3, max_length=100)
    phone_number: str = Field(..., pattern=r"^[0-9]{10}$")
    email: EmailStr
    date_of_birth: date

    # Matches the SQL constraint: 12 digits with 2 hyphens
    aadhar_no: str = Field(..., pattern=r"^\d{4}-\d{4}-\d{4}$")
    pan_no: Optional[str] = None

    nominee_name: str = Field(..., min_length=3)
    nominee_relation: str

    # Matches the SQL check constraint (1-28)
    monthly_installment_date: int = Field(10, ge=1, le=28)

    @field_validator("pan_no")
    @classmethod
    def validate_pan(cls, v: Optional[str]) -> Optional[str]:
        """Automatically capitalizes PAN and checks format before DB entry"""
        if v:
            v = v.upper()
            if not re.match(r"^[A-Z]{5}[0-9]{4}[A-Z]{1}$", v):
                raise ValueError("Invalid PAN format. Expected ABCDE1234F")
        return v


# --- 2. CREATE SCHEMA ---
# This is the "Contract" for the Registration Form.
class MemberCreate(MemberBase):
    # This field is only used during the initial API call to set the opening balance
    initial_deposit: Decimal = Field(..., ge=500)

    # URLs for the files uploaded to Supabase Storage
    photo_url: HttpUrl
    aadhar_url: HttpUrl
    pan_url: Optional[HttpUrl] = None


# --- 3. UPDATE SCHEMA ---
# All fields are Optional. Used when editing a profile.
class MemberUpdate(BaseModel):
    full_name: Optional[str] = None
    phone_number: Optional[str] = None
    email: Optional[EmailStr] = None
    is_active: Optional[bool] = None
    nominee_name: Optional[str] = None
    nominee_relation: Optional[str] = None
    monthly_installment_date: Optional[int] = Field(None, ge=1, le=28)


# --- 3b. STATUS UPDATE SCHEMA (for /status endpoint) ---
class MemberStatusUpdate(BaseModel):
    is_active: bool


# --- 4. RESPONSE SCHEMA ---
# What the Backend sends to the Next.js Frontend.
class MemberResponse(MemberBase):
    account_number: str  # Generated by services/id_generator.py

    # Financial snapshots
    balance: Decimal
    penalty_amount: Decimal

    # Metadata and Status
    is_active: bool
    joining_date: date
    photo_url: HttpUrl
    aadhar_url: HttpUrl
    pan_url: Optional[HttpUrl] = None

    # Audit timestamps from the DB
    created_at: datetime
    updated_at: datetime

    # This allows Pydantic to convert Supabase/PostgreSQL rows into JSON automatically
    model_config = ConfigDict(from_attributes=True)

